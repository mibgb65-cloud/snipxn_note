type I18nState = {
  hydrated: boolean;
  language: AppLanguage;
  hydrateLanguage: () => Promise<void>;
  setLanguage: (language: AppLanguage) => Promise<void>;
};

export const useI18nStore = create<I18nState>((set, get) => ({
  hydrated: false,
  language: DEFAULT_APP_LANGUAGE,
  hydrateLanguage: async () => {
    if (get().hydrated) {
      return;
    }

    const language = await getStoredAppLanguage();
    set({ hydrated: true, language });
  },
  setLanguage: async (language: AppLanguage) => {
    set({ language, hydrated: true });
    await setStoredAppLanguage(language);
  },
}));

export function getCurrentAppLanguage(): AppLanguage {
  return useI18nStore.getState().language;
}

export function translateLiteral(text: string, language: AppLanguage = getCurrentAppLanguage()): string {
  if (language !== 'en-US') {
    return text;
  }

  return ENGLISH_LITERALS[text] ?? text;
}

export function useI18n() {
  const language = useI18nStore(state => state.language);
  const setLanguage = useI18nStore(state => state.setLanguage);
  const t = useCallback(
    (text: string) => translateLiteral(text, language),
    [language],
  );

  return {
    isEnglish: language === 'en-US',
    language,
    setLanguage,
    t,
  };
}
